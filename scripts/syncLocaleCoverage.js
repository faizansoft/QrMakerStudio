/**
 * Keeps locale coverage honest: a (locale, path) pair only gets a real URL,
 * sitemap entry and hreflang when its BODY is translated, not just its hero.
 *
 * This script derives that set from scripts/richContentI18n/<locale>.js and
 * writes two things, then the build continues as normal:
 *   1. scripts/localeBodyCoverage.js — the static list routeMetaI18nData.js
 *      filters on. Kept as a small plain file so the browser bundle never
 *      imports the large per-locale body translations.
 *   2. vercel.json — a 301 from every locale URL that has no translated body
 *      to its English equivalent, so old links land on content instead of 404.
 *
 * Run automatically by `npm run build`. Do not edit the generated sections by hand.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { ROUTED_LOCALES, ROUTE_META_I18N_ALL as ROUTE_META_I18N } from './routeMetaI18nAll.js';
import { ROUTE_CONTENT } from './routeContent.js';
import { RICH_CONTENT_I18N } from './richContentI18nData.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');

// Pages whose React component still renders hard-coded English JSX (or English
// article bodies from blogData.ts) on the client. The client uses createRoot,
// so it replaces the prerendered translated HTML: serving these in a locale
// would show a translated title over English copy. Their translations stay in
// scripts/richContentI18n/<locale>.js and go live when the component reads
// localized content. Until then these locale URLs 301 to English.
// Empty: the five tool apps read their copy from constants/toolI18n/<tool>/<locale>.ts,
// and /pdf-qr-code-generator now renders PDFToQRPage. Add a path here only if a
// page component goes back to hard-coded English.
const NOT_CLIENT_LOCALIZED = new Set([]);

// Coverage is derived from the raw, unfiltered hero translations, so this
// script must read ROUTE_META_I18N before the filter in routeMetaI18nData.js.
const coverage = {};
for (const locale of ROUTED_LOCALES) {
  coverage[locale] = Object.keys(RICH_CONTENT_I18N[locale] || {})
    .filter((p) => ROUTE_META_I18N[locale]?.[p])
    .filter((p) => !NOT_CLIENT_LOCALIZED.has(p))
    .sort();
}

const coverageFile = path.join(__dirname, 'localeBodyCoverage.js');
fs.writeFileSync(
  coverageFile,
  `/* AUTO-GENERATED by scripts/syncLocaleCoverage.js — do not edit. */\n` +
    `export const LOCALE_BODY_PATHS = ${JSON.stringify(coverage, null, 2)};\n`,
  'utf8'
);

// 301 every untranslated locale URL to the English page. Indexable English
// routes only, since noindex routes never had locale variants.
const englishPaths = ROUTE_CONTENT.filter((r) => !r.noindex).map((r) => r.path);
const redirects = [];
for (const locale of ROUTED_LOCALES) {
  const covered = new Set(coverage[locale]);
  for (const p of englishPaths) {
    if (covered.has(p)) continue;
    if (!ROUTE_META_I18N[locale]?.[p]) continue; // never had a locale URL
    const source = p === '/' ? `/${locale}` : `/${locale}${p}`;
    const destination = p === '/' ? '/' : p;
    redirects.push({ source, destination, permanent: true });
  }
}

const vercelFile = path.join(rootDir, 'vercel.json');
const vercel = JSON.parse(fs.readFileSync(vercelFile, 'utf8'));
// Keep the host redirect (index 0); replace only the generated locale ones.
const hostRedirects = (vercel.redirects || []).filter((r) => r.has);
vercel.redirects = [...hostRedirects, ...redirects];
fs.writeFileSync(vercelFile, JSON.stringify(vercel, null, 2) + '\n', 'utf8');

const total = Object.values(coverage).reduce((n, a) => n + a.length, 0);
console.log(
  `🌐 Locale coverage: ${total} translated-body pages across ${ROUTED_LOCALES.length} locales; ` +
    `${redirects.length} untranslated locale URLs now 301 to English.`
);
